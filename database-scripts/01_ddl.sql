-- 1. USUARIO
CREATE TABLE USUARIO (
    id_usuario NUMBER(10) NOT NULL,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(150) NOT NULL,
    senha_hash VARCHAR2(255) NOT NULL,
    perfil VARCHAR2(15) NOT NULL,
    data_cadastro DATE NOT NULL,
    ativo CHAR(1) NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (id_usuario)
);

-- 2. CIDADE
CREATE TABLE CIDADE (
    id_cidade NUMBER(10) NOT NULL,
    nome VARCHAR2(100) NOT NULL,
    uf CHAR(2) NOT NULL,
    CONSTRAINT PK_CIDADE PRIMARY KEY (id_cidade)
);

-- 3. BAIRRO
CREATE TABLE BAIRRO (
    id_bairro NUMBER(10) NOT NULL,
    nome VARCHAR2(100) NOT NULL,
    id_cidade NUMBER(10) NOT NULL,
    CONSTRAINT PK_BAIRRO PRIMARY KEY (id_bairro),
    CONSTRAINT FK_BAIRRO_CIDADE FOREIGN KEY (id_cidade)
        REFERENCES CIDADE(id_cidade)
);

-- 4. REGISTRO
CREATE TABLE REGISTRO (
    id_registro NUMBER(10) NOT NULL,
    id_usuario_autor NUMBER(10) NOT NULL,
    id_bairro NUMBER(10) NOT NULL,
    id_admin_moderador NUMBER(10),
    tipo_registro VARCHAR2(20) NOT NULL,
    titulo VARCHAR2(150) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    endereco VARCHAR2(200) NOT NULL,
    data_cadastro DATE NOT NULL,
    status_moderacao VARCHAR2(20) NOT NULL,
    data_moderacao DATE,
    CONSTRAINT PK_REGISTRO PRIMARY KEY (id_registro),
    CONSTRAINT FK_REG_AUTOR FOREIGN KEY (id_usuario_autor)
        REFERENCES USUARIO(id_usuario),
    CONSTRAINT FK_REG_BAIRRO FOREIGN KEY (id_bairro)
        REFERENCES BAIRRO(id_bairro),
    CONSTRAINT FK_REG_ADMIN FOREIGN KEY (id_admin_moderador)
        REFERENCES USUARIO(id_usuario)
);

-- 5. ESTABELECIMENTO
CREATE TABLE ESTABELECIMENTO (
    id_registro NUMBER(10) NOT NULL,
    categoria VARCHAR2(60) NOT NULL,
    CONSTRAINT PK_ESTABELECIMENTO PRIMARY KEY (id_registro),
    CONSTRAINT FK_ESTAB_REG FOREIGN KEY (id_registro)
        REFERENCES REGISTRO(id_registro)
);

-- 6. AREA_ACESSIVEL
CREATE TABLE AREA_ACESSIVEL (
    id_registro NUMBER(10) NOT NULL,
    tipo_area VARCHAR2(60) NOT NULL,
    caracteristicas VARCHAR2(500) NOT NULL,
    CONSTRAINT PK_AREA PRIMARY KEY (id_registro),
    CONSTRAINT FK_AREA_REG FOREIGN KEY (id_registro)
        REFERENCES REGISTRO(id_registro)
);

-- 7. BARREIRA
CREATE TABLE BARREIRA (
    id_registro NUMBER(10) NOT NULL,
    tipo_barreira VARCHAR2(60) NOT NULL,
    status_barreira VARCHAR2(25) NOT NULL,
    CONSTRAINT PK_BARREIRA PRIMARY KEY (id_registro),
    CONSTRAINT FK_BARREIRA_REG FOREIGN KEY (id_registro)
        REFERENCES REGISTRO(id_registro)
);

-- 8. RECURSO_ACESSIBILIDADE
CREATE TABLE RECURSO_ACESSIBILIDADE (
    id_recurso NUMBER(10) NOT NULL,
    nome VARCHAR2(100) NOT NULL,
    descricao VARCHAR2(300),
    CONSTRAINT PK_RECURSO PRIMARY KEY (id_recurso)
);

-- 9. ESTABELECIMENTO_RECURSO
CREATE TABLE ESTABELECIMENTO_RECURSO (
    id_estabelecimento NUMBER(10) NOT NULL,
    id_recurso NUMBER(10) NOT NULL,
    CONSTRAINT PK_ESTAB_RECURSO PRIMARY KEY
        (id_estabelecimento, id_recurso),
    CONSTRAINT FK_ER_ESTAB FOREIGN KEY (id_estabelecimento)
        REFERENCES ESTABELECIMENTO(id_registro),
    CONSTRAINT FK_ER_RECURSO FOREIGN KEY (id_recurso)
        REFERENCES RECURSO_ACESSIBILIDADE(id_recurso)
);

-- 10. AVALIACAO
CREATE TABLE AVALIACAO (
    id_avaliacao NUMBER(10) NOT NULL,
    id_usuario NUMBER(10) NOT NULL,
    id_estabelecimento NUMBER(10) NOT NULL,
    nota NUMBER(1) NOT NULL,
    comentario VARCHAR2(500),
    data_avaliacao DATE NOT NULL,
    CONSTRAINT PK_AVALIACAO PRIMARY KEY (id_avaliacao),
    CONSTRAINT FK_AVAL_USUARIO FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario),
    CONSTRAINT FK_AVAL_ESTAB FOREIGN KEY (id_estabelecimento)
        REFERENCES ESTABELECIMENTO(id_registro)
);

-- 11. VALIDACAO
CREATE TABLE VALIDACAO (
    id_validacao NUMBER(10) NOT NULL,
    id_usuario NUMBER(10) NOT NULL,
    id_registro NUMBER(10) NOT NULL,
    tipo_validacao VARCHAR2(15) NOT NULL,
    comentario VARCHAR2(500),
    data_validacao DATE NOT NULL,
    CONSTRAINT PK_VALIDACAO PRIMARY KEY (id_validacao),
    CONSTRAINT FK_VAL_USUARIO FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario),
    CONSTRAINT FK_VAL_REG FOREIGN KEY (id_registro)
        REFERENCES REGISTRO(id_registro)
);

-- 12. RELATO_RESOLUCAO
CREATE TABLE RELATO_RESOLUCAO (
    id_relato NUMBER(10) NOT NULL,
    id_barreira NUMBER(10) NOT NULL,
    id_usuario NUMBER(10) NOT NULL,
    id_admin_revisor NUMBER(10),
    descricao VARCHAR2(500) NOT NULL,
    data_relato DATE NOT NULL,
    status_analise VARCHAR2(20) NOT NULL,
    data_analise DATE,
    CONSTRAINT PK_RELATO PRIMARY KEY (id_relato),
    CONSTRAINT FK_REL_BARREIRA FOREIGN KEY (id_barreira)
        REFERENCES BARREIRA(id_registro),
    CONSTRAINT FK_REL_USUARIO FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario),
    CONSTRAINT FK_REL_ADMIN FOREIGN KEY (id_admin_revisor)
        REFERENCES USUARIO(id_usuario)
);

